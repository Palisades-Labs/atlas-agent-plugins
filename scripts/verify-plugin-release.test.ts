describe("command-line boundary", () => {
  test("prints help without reading release inputs", () => {
    const result = Bun.spawnSync(["bun", SCRIPT, "--help"], {
      stdout: "pipe",
      stderr: "pipe",
    });
    expect(result.exitCode).toBe(0);
    expect(result.stdout.toString()).toContain("--release-checksums");
    expect(result.stderr.toString()).toBe("");
  });

  test("fails closed on an unknown argument", () => {
    const result = Bun.spawnSync(["bun", SCRIPT, "--surprise", "value"], {
      stdout: "pipe",
      stderr: "pipe",
    });
    expect(result.exitCode).toBe(1);
    expect(result.stderr.toString()).toContain("[unknown_argument]");
    expect(result.stderr.toString()).not.toContain("\n    at ");
  });

  test("fails closed on a missing required argument", () => {
    const result = Bun.spawnSync(
      [
        "bun",
        SCRIPT,
        "--root",
        ".",
        "--tag",
        PLUGIN_TAG,
        "--metadata",
        "metadata.json",
      ],
      { stdout: "pipe", stderr: "pipe" },
    );
    expect(result.exitCode).toBe(1);
    expect(result.stderr.toString()).toContain(
      "[missing_argument] --release-checksums is required",
    );
    expect(result.stderr.toString()).not.toContain("\n    at ");
  });

  test("rejects an explicitly empty GitHub output path", () => {
    const result = Bun.spawnSync(
      [
        "bun",
        SCRIPT,
        "--root",
        ".",
        "--tag",
        PLUGIN_TAG,
        "--metadata",
        "metadata.json",
        "--release-checksums",
        "checksums.txt",
        "--github-output",
        "",
      ],
      { stdout: "pipe", stderr: "pipe" },
    );
    expect(result.exitCode).toBe(1);
    expect(result.stderr.toString()).toContain(
      "[missing_argument_value] --github-output requires a value",
    );
  });
});
